      <h2 class="fw-bold mb-3">Tentang SISAPI</h2>
      <p>SISAPI (Sistem Informasi dan Marketplace Peternakan Indonesia) adalah platform yang mempertemukan peternak dan calon pembeli ternak di seluruh Indonesia. Berbeda dengan marketplace pada umumnya, seluruh data ternak yang tampil di SISAPI telah melalui proses verifikasi berjenjang oleh Admin Dinas Peternakan, sehingga informasi yang tersedia lebih valid dan terpercaya.</p>
      <p>SISAPI tidak menyediakan fitur pembayaran online maupun keranjang belanja. Platform ini murni berfungsi sebagai media promosi dan penghubung — transaksi dan negosiasi harga dilakukan langsung antara pembeli dan penjual melalui WhatsApp.</p>
      <h5 class="fw-bold mt-4">Alur Verifikasi Berjenjang</h5>
      <ol>
        <li>Peternak mendaftar dan melengkapi data identitas beserta dokumen pendukung.</li>
        <li>Admin Dinas memverifikasi kelengkapan dan keabsahan data peternak.</li>
        <li>Setelah disetujui, peternak dapat mengunggah data ternak.</li>
        <li>Setiap ternak yang diunggah kembali diverifikasi Admin Dinas sebelum tampil ke publik.</li>
        <li>Seluruh proses verifikasi tercatat dalam log aktivitas (audit trail) yang dapat ditelusuri.</li>
      </ol>
